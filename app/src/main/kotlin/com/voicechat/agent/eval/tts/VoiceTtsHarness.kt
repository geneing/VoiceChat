package com.voicechat.agent.eval.tts

import com.voicechat.agent.contracts.TextToSpeech
import com.voicechat.agent.contracts.TtsEvent
import com.voicechat.agent.diagnostics.MonotonicClock
import com.voicechat.agent.diagnostics.SystemMonotonicClock
import com.voicechat.agent.domain.UtteranceId
import com.voicechat.agent.eval.LatencyMetric
import com.voicechat.agent.eval.LatencyReport
import com.voicechat.agent.eval.LatencySample
import com.voicechat.agent.eval.MeasurementConditions
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.flow.collect

/**
 * What one measured TTS attempt produced.
 *
 * Durations are monotonic and measured from just before [TextToSpeech.speak] is
 * collected, so they include the adapter's outbound mapping and the engine's own
 * synthesis/playback. [firstAudibleMillis] is the time to the contract's
 * first-audible `Started` event (what the user hears), not when `speak()`
 * returned; [deliveredMillis] is when the utterance finished playing in full.
 */
data class VoiceTtsRun(
    val text: String,
    val characters: Int,
    val firstAudibleMillis: Long?,
    val deliveredMillis: Long?,
    val completed: Boolean,
    val failure: String?,
)

/**
 * Every attempt for one [text], with the medians the voice decision is made on.
 *
 * A single playback is not a latency measurement, so the harness repeats and
 * reports the median, never one number.
 */
class VoiceTtsCaseResult(
    val text: String,
    val runs: List<VoiceTtsRun>,
) {
    /** Median time to first audible audio over the attempts that reported it. */
    val medianFirstAudibleMillis: Long? get() = runs.mapNotNull { it.firstAudibleMillis }.median()

    /** Median time to full delivery over the attempts that delivered. */
    val medianDeliveredMillis: Long? get() = runs.mapNotNull { it.deliveredMillis }.median()

    /** True when every attempt delivered the utterance in full. */
    val allCompleted: Boolean get() = runs.all { it.completed }

    /** The distinct failure descriptions, for the record. */
    val failures: List<String> get() = runs.mapNotNull { it.failure }.distinct()

    private fun List<Long>.median(): Long? =
        if (isEmpty()) {
            null
        } else {
            val sorted = sorted()
            if (sorted.size % 2 == 1) {
                sorted[sorted.size / 2]
            } else {
                (sorted[sorted.size / 2 - 1] + sorted[sorted.size / 2]) / 2
            }
        }
}

/**
 * The measured set: the per-utterance TTS timings, rendered as the markdown
 * record the harness writes.
 *
 * [latency] carries the aggregated `tts_first_audible`/`tts_completion`
 * metrics, or `null` when no attempt produced a measurable duration (an
 * unmeasured stage is absent rather than a fabricated zero).
 */
class VoiceTtsHarnessReport(
    val conditions: MeasurementConditions,
    val results: List<VoiceTtsCaseResult>,
    val latency: LatencyReport?,
    val recordedAt: String,
) {
    /** The summary table: medians per text, with the number of attempts. */
    fun summaryMarkdown(): String {
        val header =
            "| Text | Attempts | First audible median (ms) | Delivered median (ms) | Characters | Result |"
        val rule = "| --- | --- | --- | --- | --- | --- |"
        val rows =
            results.map { result ->
                val outcome =
                    if (result.allCompleted) {
                        "delivered"
                    } else {
                        "FAILED (${result.failures.joinToString(separator = "; ")})"
                    }
                "| ${escape(result.text)} | ${result.runs.size} | ${result.medianFirstAudibleMillis.ms()} | " +
                    "${result.medianDeliveredMillis.ms()} | ${result.runs.firstOrNull()?.characters ?: 0} | $outcome |"
            }
        return (listOf(header, rule) + rows).joinToString(separator = "\n")
    }

    /** The whole record: method, conditions, the aggregated latency, and the per-text rows. */
    fun toMarkdown(): String =
        buildString {
            appendLine("# Voice TTS Harness Run — $recordedAt")
            appendLine()
            appendLine("Generated by `com.voicechat.agent.eval.tts.VoiceTtsHarness`, which drives the")
            appendLine("on-device M11 `TextToSpeech` contract and measures what the voice loop waits")
            appendLine("through for the TTS stage. Durations are monotonic from the `speak()` call, so")
            appendLine("they cover synthesis and playback, and `tts_first_audible` is when audio was")
            appendLine("actually audible. The record is only as strong as the conditions it was taken")
            appendLine("under; a host/emulator run is not a device claim (docs/evaluation.md).")
            appendLine()
            appendLine("## Conditions")
            appendLine()
            appendLine(conditions.summarize())
            appendLine()
            appendLine("## Summary")
            appendLine()
            appendLine(summaryMarkdown())
            appendLine()
            appendLine("## Latency")
            appendLine()
            appendLine(latency?.toMarkdown() ?: "No attempt produced a measurable duration.")
            appendLine()
            appendLine("## Attempts")
            appendLine()
            results.forEach { result ->
                appendLine("### ${escape(result.text)}")
                appendLine()
                result.runs.forEachIndexed { index, run ->
                    appendLine(
                        "- Attempt ${index + 1}: first audible ${run.firstAudibleMillis.ms()} ms, " +
                            "delivered ${run.deliveredMillis.ms()} ms, ${run.characters} chars, " +
                            "completed=${run.completed}" + (run.failure?.let { ", failure=$it" } ?: ""),
                    )
                }
                appendLine()
            }
        }

    private fun Long?.ms(): String = this?.toString() ?: "-"

    private fun escape(text: String): String = text.replace("|", "\\|").replace("\n", " ")
}

/**
 * The TTS-stage harness: speaks the same fixed texts through a
 * [TextToSpeech] instance [repeats] times each and records the timings a voice
 * loop would see.
 *
 * It is deliberately independent of the recognizer and the LLM so the on-device
 * speech API can be measured (its selected engine/voice, time to first audible
 * audio, and full-playback time) without a microphone or a provider. It never
 * asserts on the spoken text; only timing, counts, and the typed outcome.
 */
class VoiceTtsHarness(
    private val textToSpeech: TextToSpeech,
    private val conditions: MeasurementConditions,
    private val now: () -> String,
    private val clock: MonotonicClock = SystemMonotonicClock,
) {
    /** Runs every [texts] entry [repeats] times and returns the record. */
    suspend fun run(
        texts: List<String> = VoiceTtsHarnessCases.TTS_TEXTS,
        repeats: Int = DEFAULT_REPEATS,
    ): VoiceTtsHarnessReport {
        require(texts.isNotEmpty()) { "the TTS harness needs at least one text" }
        require(repeats >= 1) { "repeats must be at least 1" }
        val results =
            texts.mapIndexed { index, text ->
                VoiceTtsCaseResult(text = text, runs = (1..repeats).map { attempt -> runAttempt(index, attempt, text) })
            }
        val samples =
            buildList {
                results.forEach { result ->
                    result.runs.forEach { run ->
                        run.firstAudibleMillis?.let {
                            add(LatencySample(LatencyMetric.TTS_FIRST_AUDIBLE, it * NANOS_PER_MILLI))
                        }
                        run.deliveredMillis?.let {
                            add(LatencySample(LatencyMetric.TTS_COMPLETION, it * NANOS_PER_MILLI))
                        }
                    }
                }
            }
        return VoiceTtsHarnessReport(
            conditions = conditions,
            results = results,
            latency = if (samples.isEmpty()) null else LatencyReport(samples, conditions),
            recordedAt = now(),
        )
    }

    private suspend fun runAttempt(
        index: Int,
        attempt: Int,
        text: String,
    ): VoiceTtsRun {
        val utteranceId = UtteranceId("tts-harness-$index-$attempt")
        val startedAt = clock.nanoTime()
        var firstAudible: Long? = null
        var delivered: Long? = null
        var completed = false
        var failure: String? = null
        try {
            textToSpeech.speak(text, utteranceId).collect { event ->
                when (event) {
                    is TtsEvent.Queued -> {
                        Unit
                    }

                    is TtsEvent.Started -> {
                        if (firstAudible == null) firstAudible = elapsedMillis(startedAt)
                    }

                    is TtsEvent.Delivered -> {
                        completed = true
                        delivered = elapsedMillis(startedAt)
                    }

                    is TtsEvent.Interrupted -> {
                        failure = "interrupted"
                    }

                    is TtsEvent.Failed -> {
                        failure = event.error.code.name
                    }
                }
            }
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (thrown: Throwable) {
            // A thrown engine/adapter error is still a measured outcome, not a
            // reason to lose the other attempts.
            return VoiceTtsRun(
                text = text,
                characters = text.length,
                firstAudibleMillis = firstAudible,
                deliveredMillis = delivered,
                completed = false,
                failure = "threw ${thrown.javaClass.simpleName}",
            )
        }
        return VoiceTtsRun(
            text = text,
            characters = text.length,
            firstAudibleMillis = firstAudible,
            deliveredMillis = delivered,
            completed = completed,
            failure = failure,
        )
    }

    private fun elapsedMillis(startedAtNanos: Long): Long = (clock.nanoTime() - startedAtNanos) / NANOS_PER_MILLI

    companion object {
        /** Attempts per text when the caller does not say otherwise. */
        const val DEFAULT_REPEATS: Int = 3

        private const val NANOS_PER_MILLI: Long = 1_000_000L
    }
}

/**
 * The texts and defaults the TTS harness measures.
 *
 * The same definition is used by the host harness (`VoiceTtsHarnessTest`) and
 * the on-device harness (`VoiceTtsHarnessInstrumentedTest`), so a device run
 * measures exactly what the host run measured. The texts are ordinary
 * assistant-shaped sentences of different lengths, so a first-audible timing
 * reflects a realistic utterance rather than a single word.
 */
object VoiceTtsHarnessCases {
    /** Short, medium, and long assistant-shaped sentences. */
    val TTS_TEXTS: List<String> =
        listOf(
            "The weather in Yosemite will be clear this weekend.",
            "Take the Mist Trail to the top of Vernal Fall, then continue to Nevada Fall.",
            "Start early, because the parking lot fills by seven thirty in the morning on a summer weekend.",
        )
}
